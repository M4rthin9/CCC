import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {insertStatement,insertBatches,columns} from './prisoner-recovery-core.mjs';
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE prisoners(prisonerId TEXT PRIMARY KEY,prisonerName TEXT,wing TEXT,status TEXT,vinaiDate TEXT,note TEXT)');
const row=(id,name,note='')=>({prisonerId:id,prisonerName:name,wing:'3',status:'',vinaiDate:'',note});
const current=row('1','Current name','Updated today');
db.exec(insertStatement([current]));
const lost=[row('2',"O'Name",'Thai ภาษาไทย; -- SQL text'),row('3','ทดสอบ','line one\nline two')];
const recovered=[row('1','Outdated name'),...lost];
db.exec(insertStatement(recovered));
assert.deepEqual({...db.prepare("SELECT * FROM prisoners WHERE prisonerId='1'").get()},current);
for(const expected of lost) assert.deepEqual({...db.prepare('SELECT * FROM prisoners WHERE prisonerId=?').get(expected.prisonerId)},expected);
db.exec(insertStatement(recovered));
assert.equal(db.prepare('SELECT count(*) AS n FROM prisoners').get().n,3);
const large=Array.from({length:300},(_,i)=>row(String(i),'ชื่อผู้ต้องขัง','ข้อความ'.repeat(250)));
const batches=insertBatches(large);
assert.equal(batches.flat().length,300);
assert(batches.every(batch=>batch.length<=100 && Buffer.byteLength(insertStatement(batch),'utf8')<=60000));
assert.equal(columns.length,6);
console.log('Recovery checks passed: existing row preserved, exact fields restored, SQL escaping, repeat safety, statement size bounds.');
